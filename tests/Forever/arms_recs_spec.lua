-- tests/Forever/arms_recs_spec.lua (audit first wave, Task 3): every recommendation slot of every Update over the seeds
-- 1-3 Arms gate (both instances: ours and the oracle) equals the fixture recorded on the base commit, before the
-- upstream performance edits (State.lua's memo, query_time first). Record with ARMS_RECS=record (rewrites the fixture).
-- The fixture is run-length: an entry { instance, update index, "name1 name2 ..." } only where an instance's queue
-- changed from its previous Update, and the Update counts at the end, so equal fixtures mean equal full sequences.
local loop = require("Game.harness.loop")
local ww = require("Forever.helpers.warrior_world")
local gate = require("Forever.helpers.arms_gate")

local PATH = "tests/Forever/fixtures/arms_recs_seeds1-3.lua"

local function record()
    local L = loop.new(ww)
    local out = { changes = {}, updates = {} }
    for name, H in pairs({ us = L.us, oracle = L.oracle }) do
        local hk, n, last = H.Hekili, 0, nil
        local upd = hk.Update
        hk.Update = function(...)
            local r = upd(...)
            n = n + 1
            local p, names = hk.Engine.Output.Primary, {}
            for i = 1, p.count do
                names[i] = tostring(p.recs[i].actionName)
            end
            local s = table.concat(names, " ")
            if s ~= last then
                out.changes[#out.changes + 1] = { name, n, s }
                last = s
            end
            out.updates[name] = n
            return r
        end
    end
    local m = loop.tally(L, 3)
    local line = loop.line(m)
    print("\nArms solo: " .. line .. " [seeds 1-3" .. (os.getenv("ARMS_RECS") == "record" and ", recorded]" or "]"))
    gate.gate(m, loop.summary(m), line)
    return out
end

local function write(rec)
    local f = assert(io.open(PATH, "w"))
    local head = io.popen("git rev-parse --short HEAD"):read("*l")
    f:write(("-- Generated by tests/Forever/arms_recs_spec.lua (ARMS_RECS=record) on %s: do not edit.\n"):format(head))
    f:write("return {\n    changes = {\n")
    for _, c in ipairs(rec.changes) do
        f:write(('        { "%s", %d, "%s" },\n'):format(c[1], c[2], c[3]))
    end
    f:write(("    },\n    updates = { oracle = %d, us = %d },\n}\n"):format(rec.updates.oracle, rec.updates.us))
    f:close()
end

describe("the seeds 1-3 Arms gate's recommendations #slow", function()
    it("match the base commit's fixture at every slot of every Update, ours and the oracle's", function()
        local rec = record()
        if os.getenv("ARMS_RECS") == "record" then
            write(rec)
        end
        local want = dofile(PATH)
        assert.are.same(want.updates, rec.updates)
        assert.are.equal(#want.changes, #rec.changes)
        for i, c in ipairs(want.changes) do
            assert.are.same(c, rec.changes[i], "change " .. i)
        end
    end)
end)
