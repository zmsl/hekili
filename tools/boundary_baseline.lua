-- tools/boundary_baseline.lua: writes tests/boundary_baseline.lua, the per-file count of each content name or ID
-- (tests/boundary_lib.lua's leaks) that stock Hekili's src/Hekili/Engine/Sim/** already uses, for boundary_spec's Sim
-- check. Run from the repository root: .lua/bin/lua tools/boundary_baseline.lua
-- Regenerate only when removing an inherited leak, never to admit one.
package.path = "./src/Hekili/?.lua;./tests/?.lua;./?.lua;" .. package.path
local B = require("boundary_lib")

local c = B.content()
local words = B.nameWords(c.keys)
local out = {
    "-- tests/boundary_baseline.lua: generated by tools/boundary_baseline.lua (per Engine/Sim file, each content name's",
    "-- count). Regenerate only when removing an inherited leak; never to admit one",
    "-- (except a pack's pseudo-spec Constants row).",
    "return {",
}
for _, path in ipairs(B.coreFiles({ "src/Hekili/Engine/Sim" }, {})) do
    local n = B.counts(path, c, words)
    local tokens = {}
    for token in pairs(n) do
        tokens[#tokens + 1] = token
    end
    table.sort(tokens)
    -- StyLua's own layout (an empty table on one line), so `make fmt` never rewrites the file
    out[#out + 1] = ('    ["%s"] = {%s'):format(path, #tokens == 0 and "}," or "")
    for _, token in ipairs(tokens) do
        out[#out + 1] = ('        ["%s"] = %d,'):format(token, n[token])
    end
    if #tokens > 0 then
        out[#out + 1] = "    },"
    end
end
out[#out + 1] = "}"
local f = assert(io.open("tests/boundary_baseline.lua", "w"))
f:write(table.concat(out, "\n"), "\n")
f:close()
