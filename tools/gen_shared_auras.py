#!/usr/bin/env python3
"""Generates src/Hekili_Shared/Shared/ItemAuras.lua: the shared (item, consumable, enchant) auras the wowsims pin registers.

NOT WIRED into Hekili_Shared.toc (see aura-lane-shared-report.md Round 2: tracking 230 more auras moves timing fixtures and overflows the CDM harness). Dev-only: `make shared-auras PIN=<wowsims checkout>`. Reads <PIN>/sim/siml/names.json (shared.aura: key -> spellId) and
$WOW_DB2 (default ~/.local/share/wow-db2/forever/current.sqlite, view spell_info) for each id's duration and stack cap.
A duration of 0 or less is until cancelled (3600, as Shared/Auras.lua's bloodlust); stacks are at least 1. A second key
for an id already taken is skipped (the first in key order keeps it). A castable spell (a class, or a power cost) is
skipped: its id is an ability's, and an aura on the same id would read as that ability's own. Every key ends in
its id (unless it already does), so none can shadow a state name (`haste`, `focus`) or a class's own key.
"""
import json
import os
import sqlite3
import sys

OUT = "src/Hekili_Shared/Shared/ItemAuras.lua"
HEAD = """-- Hekili_Shared/Shared/ItemAuras.lua: GENERATED by tools/gen_shared_auras.py (`make shared-auras`); do not edit.
-- The shared item, consumable and enchant auras the wowsims pin registers (sim/siml/names.json shared.aura), through
-- Engine/Schema/Shared.lua into `all` (a class's own key wins): id, duration (DB2 spell_info; 3600 when until
-- cancelled) and stack cap. { key, id, duration, max_stack }. Observed only: nothing here is predicted. NOT LOADED: not in
-- Hekili_Shared.toc, because the belief tracks every registered aura (230 more move the timing fixtures).

local shared = Hekili:NewShared()

local auras = {
"""
TAIL = """}

for i = 1, #auras do
    local a = auras[i]
    shared:RegisterAura(a[1], { id = a[2], duration = a[3], max_stack = a[4] })
end
"""


def rows(names, lookup):
    """[(key, id, duration seconds, max_stack)] for names["shared"]["aura"], keys sorted, one row per id."""
    out, seen = [], set()
    for key, v in sorted(names["shared"]["aura"].items()):
        sid = v["spellId"]
        if sid in seen:
            continue
        seen.add(sid)
        ms, stacks, castable = lookup(sid)
        if castable:
            continue
        secs = (ms or 0) / 1000
        key = key if key.endswith(str(sid)) else "%s_%d" % (key, sid)
        out.append((key, sid, secs if secs > 0 else 3600, max(1, stacks or 1)))
    return out


def render(rs):
    return HEAD + "".join('    { "%s", %d, %g, %d },\n' % r for r in rs) + TAIL


def main(pin):
    names = json.load(open(os.path.join(pin, "sim/siml/names.json")))
    db = sqlite3.connect(os.path.expanduser(os.environ.get("WOW_DB2", "~/.local/share/wow-db2/forever/current.sqlite")))

    def lookup(sid):
        r = db.execute("select duration_ms, max_stacks, classes, power from spell_info where id = ?", (sid,)).fetchone()
        return (r[0], r[1], bool(r[2] or r[3])) if r else (0, 1, False)

    with open(OUT, "w") as f:
        f.write(render(rows(names, lookup)))


if __name__ == "__main__":
    main(sys.argv[1])
