-- tools/cdm_fixtures.lua: writes tests/Forever/fixtures/cdm/<class>.lua, one per class, from the owner's ForeverProbe
-- export (the SavedVariables file holding ForeverProbeDB.cdm[CLASS]: every Cooldown Manager entry of categories 0-8,
-- unlearned included, and .talents: the live talent tree). tests/Forever/cdm_map_spec.lua maps each entry against its
-- class pack and compares the tree with the pack's talents.
-- Regenerate: on each character the owner runs /fprobe export, then /reload (the client writes the SavedVariables);
-- copy WTF/Account/<account>/SavedVariables/ForeverProbe.lua out of the client, then from the repo root:
--   .lua/bin/lua tools/cdm_fixtures.lua <path to ForeverProbe.lua>
-- A class missing from the export keeps its old fixture. Export values: strings "=<text>", a secret "S" (refused: export
-- out of combat), numbers plain (ForeverProbe Export.lua Val/Try).
local path = assert(arg[1], "usage: lua tools/cdm_fixtures.lua <ForeverProbe.lua SavedVariables>")
local env = {}
local chunk = assert(loadfile(path))
setfenv(chunk, env)
chunk()
local db = assert(env.ForeverProbeDB and env.ForeverProbeDB.cdm, "no ForeverProbeDB.cdm in " .. path)

local function str(x) -- an exported string, or nil (absent or "nil")
    if type(x) == "string" and x:sub(1, 1) == "=" then
        return x:sub(2)
    end
    assert(x == nil or x == "nil", "not an exported string (secret? export out of combat): " .. tostring(x))
    return nil
end

local function num(x, what) -- an exported spell ID, or nil (absent or "nil")
    if x == "nil" then
        return nil
    end
    assert(
        x == nil or type(x) == "number",
        what .. " is not a plain number (secret? export out of combat): " .. tostring(x)
    )
    return x
end

local classes = {}
for class in pairs(db) do
    classes[#classes + 1] = class
end
table.sort(classes)

for _, class in ipairs(classes) do
    local rec = db[class]
    local meta = rec.meta or {}
    local when, build = meta.when, str(meta.build and meta.build[2]) -- `when` is written plain
    local out = {
        ("-- tests/Forever/fixtures/cdm/%s.lua: the Forever client's Cooldown Manager entries for the %s (categories 0-8,"):format(
            class:lower(),
            class
        ),
        ("-- unlearned included), from the owner's in-game export of %s (build %s, level %s). Generated by"):format(
            tostring(when),
            tostring(build),
            tostring(meta.level)
        ),
        "-- tools/cdm_fixtures.lua (its header says how to regenerate); never edit by hand. Read by tests/Forever/cdm_map_spec.lua.",
        "-- Per entry, in the client's order (category, then the category set's): the cooldownID, its category, the spell's",
        "-- name, spellID, override (C_Spell.GetOverrideSpell(spellID) at export), overrideSpellID, overrideTooltipSpellID,",
        "-- linked ({ spellID, name } per linkedSpellIDs element, every rank, learned or not). `talents`: the live talent",
        "-- tree (the C_Traits walk, tree then node order), one row per node entry: node ID, entry ID, the definition's",
        "-- spellID, its name and max ranks.",
        "-- stylua: ignore",
        "return {",
        ("    class = %q, level = %s, date = %q, build = %s,"):format(
            class,
            tostring(meta.level),
            tostring(when),
            tostring(build)
        ),
        "    entries = {",
    }
    local cats = rec.cdm and rec.cdm.cats or {}
    for cat = 0, 8 do
        for _, r in ipairs(cats[cat] or {}) do
            local i = type(r.info) == "table" and r.info or {}
            local parts = { ("id = %d, cat = %d"):format(num(r.id, "id"), cat) }
            local name = str(r.name)
            if name then
                parts[#parts + 1] = ("name = %q"):format(name)
            end
            for _, f in ipairs({ "spellID", "override", "overrideSpellID", "overrideTooltipSpellID" }) do
                local v = num(f == "override" and r.override or i[f], f)
                if v then
                    parts[#parts + 1] = ("%s = %d"):format(f, v)
                end
            end
            local links = {}
            for k, l in ipairs(type(i.linkedSpellIDs) == "table" and i.linkedSpellIDs or {}) do
                links[#links + 1] = ("{ %d, %q }"):format(
                    num(l, "linked"),
                    str(r.linkedNames and r.linkedNames[k]) or "?"
                )
            end
            if #links > 0 then
                parts[#parts + 1] = "linked = { " .. table.concat(links, ", ") .. " }"
            end
            out[#out + 1] = "        { " .. table.concat(parts, ", ") .. " },"
        end
    end
    local nEntries = #out - 12 -- the header's lines
    out[#out + 1] = "    },"
    out[#out + 1] = "    talents = {"
    local nTalents = 0
    for _, tree in ipairs(rec.talents and rec.talents.trees or {}) do
        for _, node in ipairs(tree.nodes or {}) do
            for _, e in ipairs(node.entries or {}) do
                out[#out + 1] = ("        { node = %d, entry = %d, spellID = %s, name = %q, max = %s },"):format(
                    num(node.id, "node"),
                    num(e.id, "entry"),
                    tostring(num(e.def and e.def.spellID, "talent spellID")),
                    str(e.info and e.info.name) or "?",
                    tostring(num(e.entry and e.entry.maxRanks, "maxRanks"))
                )
                nTalents = nTalents + 1
            end
        end
    end
    out[#out + 1] = "    },"
    out[#out + 1] = "}"
    local file = "tests/Forever/fixtures/cdm/" .. class:lower() .. ".lua"
    local fh = assert(io.open(file, "w"))
    fh:write(table.concat(out, "\n"), "\n")
    fh:close()
    print(file, nEntries .. " entries", nTalents .. " talents")
end
